function rgbaOf(ch: string, transparentDot: boolean): [number, number, number, number] {
  if (ch === ".") return transparentDot ? [0, 0, 0, 0] : [0, 0, 0, 255];
  const c = EGA[parseInt(ch, 16)];
  if (c === undefined) throw new Error(`bad glyph "${ch}"`);
  return [(c >> 16) & 255, (c >> 8) & 255, c & 255, 255];
}

function check(name: string, art: string[]) {
  if (art.length !== TILE_SIZE) throw new Error(`${name}: ${art.length} rows, expected ${TILE_SIZE}`);
  art.forEach((row, i) => {
    if (row.length !== TILE_SIZE) throw new Error(`${name} row ${i}: ${row.length} chars, expected ${TILE_SIZE}`);
  });
}

function sheet(arts: string[][], transparentDot: boolean): Buffer {
  const w = arts.length * TILE_SIZE;
  const h = TILE_SIZE;
  const px = Buffer.alloc(w * h * 4);
  arts.forEach((art, n) => {
    for (let y = 0; y < h; y++) {
      for (let x = 0; x < TILE_SIZE; x++) {
        const o = (y * w + n * TILE_SIZE + x) * 4;
        px.set(rgbaOf(art[y]![x]!, transparentDot), o);
      }
    }
  });
  return png(w, h, px);
}

function png(w: number, h: number, rgba: Buffer): Buffer {
  const raw = Buffer.alloc((w * 4 + 1) * h);
  for (let y = 0; y < h; y++) rgba.copy(raw, y * (w * 4 + 1) + 1, y * w * 4, (y + 1) * w * 4);
  const chunk = (type: string, data: Buffer) => {
    const len = Buffer.alloc(4);
    len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type, "ascii"), data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(td));
    return Buffer.concat([len, td, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr.set([8, 6, 0, 0, 0], 8); // 8-bit RGBA
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

const ordered = [...TILE_DEFS].sort((a, b) => a.id - b.id).map((t, i) => {
  if (t.id !== i) throw new Error(`tile ids must be contiguous from 0 (gap at ${i})`);
  const art = TILES[t.key];
  if (!art) throw new Error(`no art for tile "${t.key}"`);
  check(t.key, art);
  return art;
});
SPRITES.forEach((s, i) => check(`sprite ${i}`, s));

const out = new URL("../../client/assets/", import.meta.url);
writeFileSync(new URL("tiles.png", out), sheet(ordered, false));
writeFileSync(new URL("sprites.png", out), sheet(SPRITES, true));
console.log(`wrote ${ordered.length} tiles and ${SPRITES.length} sprites to client/assets/`);
